    from pathlib import Path
    from pprint import pformat
    global RESULT_TABLE, ROW_RESULTS, ROW_TOTALS
    result=report_data(result)
    values={r['id']:report_data(r) for r in RESULT_TABLE}
    values[result['id']]=result
    RESULT_TABLE=tuple(values[c.id] for c in CASES if c.id in values)
    ROW_RESULTS=row_table(RESULT_TABLE)
    ROW_TOTALS={STATUS_LABELS[k]:sum(r['status']==k for r in ROW_RESULTS) for k in STATUS_LABELS}
    path=Path(__file__)
    source=path.read_text(encoding='utf-8')
    start=source.index('\n# BEGIN RECORDED RESULTS\n')+1
    end=source.index('\n# END RECORDED RESULTS',start)
    block='# BEGIN RECORDED RESULTS\nRESULT_TABLE = '+pformat(RESULT_TABLE,width=115,sort_dicts=False)
    block+='\nROW_RESULTS = '+pformat(ROW_RESULTS,width=115,sort_dicts=False)
